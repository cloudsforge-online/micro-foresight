// Compile src/contracts/ForesightMarket.sol into the COMMITTED artefact src/contracts/generated.ts.
//
// Committed, rather than built, because the service runs under tsx with no build step to hang a
// compile on — and because bytecode in git is bytecode a reviewer can diff. The CI job `contracts`
// re-runs this and fails on any difference, so the artefact and the source cannot drift: a change
// to the .sol that is not accompanied by a regenerated artefact is a red build, and an artefact
// edited by hand is the same red build.
//
// That guarantee rests entirely on the EXACT pin in package.json — `solc: "0.8.26"`. Loosen it to a
// caret range and the job stops proving anything: the recompile would produce different bytes on a
// different day and the diff would be noise rather than signal.
//
// Carried forward from `micro-mint/scripts/compile-contracts.mjs`, which is the precedent this
// repository was told to follow exactly. The one difference is that there are no OpenZeppelin
// imports to resolve — this contract has no dependencies, deliberately, because a parimutuel pool
// needs no token standard and no access-control library, and every import is bytecode a reviewer
// then has to take on trust.

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const solc = require('solc')

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = 'ForesightMarket.sol'
const sourcePath = resolve(root, 'src/contracts', SOURCE)
const outPath = resolve(root, 'src/contracts/generated.ts')

const sourceText = readFileSync(sourcePath, 'utf8')

const input = {
  language: 'Solidity',
  sources: { [SOURCE]: { content: sourceText } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    // The widest chain support available: `paris` avoids PUSH0, which several L2s and Hearth's own
    // EVM do not implement. A `shanghai` build would deploy fine on Ethereum and produce an invalid
    // opcode on Ember, which is a market bricked at creation with stakers' money already promised.
    evmVersion: 'paris',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
}

const output = JSON.parse(solc.compile(JSON.stringify(input)))

const errors = (output.errors ?? []).filter((e) => e.severity === 'error')
if (errors.length > 0) {
  for (const error of errors) process.stderr.write(`${error.formattedMessage}\n`)
  process.exit(1)
}

const contracts = output.contracts[SOURCE]
const names = Object.keys(contracts)
  .filter((name) => (contracts[name].evm.bytecode.object ?? '').length > 0)
  .sort()

const lines = [
  '/**',
  ' * GENERATED by scripts/compile-contracts.mjs from src/contracts/ForesightMarket.sol. Do not edit.',
  ` * solc ${solc.version()}, optimizer 200 runs, evmVersion paris.`,
  ' *',
  ' * CI recompiles and diffs this file. A hand edit here and a source change without a recompile',
  ' * are the same red build, which is the whole point of committing it.',
  ' */',
  '',
  '/** sha256 of the .sol this was compiled from. Asserted by contracts.test.ts. */',
  `export const SOURCE_SHA256 = '${createHash('sha256').update(sourceText).digest('hex')}'`,
  '',
]

for (const name of names) {
  const artefact = contracts[name]
  const bytecode = artefact.evm.bytecode.object
  lines.push(
    `export const ${name.toUpperCase()}_ABI = ${JSON.stringify(artefact.abi)} as const`,
    '',
    `export const ${name.toUpperCase()}_BYTECODE =`,
    `  '0x${bytecode}'`,
    '',
  )
}

writeFileSync(outPath, `${lines.join('\n')}`)
process.stderr.write(`wrote ${outPath} (${names.join(', ')})\n`)
